// FP07: the clients' types come from each component's published contract at the version the baseline selects. For
// every component a page module uses (its component, needs and optional ones), takes the component repository's
// contract/openapi.yaml and contract/events/ at that version's tag (the document refers to the event schemas), keeps it
// under packages/api/contracts/<component>/ (committed: a review sees what changed), and generates
// src/generated/<component>.ts with openapi-typescript. Components without a published contract are listed and
// skipped (the shell's own few calls are typed by hand, FP07).
// Usage: BE_ASSEMBLY=<the assembly project> node packages/api/scripts/generate.ts [component ...]
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import openapiTS, { astToString } from "openapi-typescript";
import { parse } from "yaml";

const repo = resolve(import.meta.dirname, "../../..");
const assembly = process.env.BE_ASSEMBLY;
if (!assembly) throw new Error("BE_ASSEMBLY: the assembly project (its components/<domain>/<name> repositories)");
const baseline = new Map<string, string>(
  (parse(readFileSync(join(repo, "baseline/standard.yaml"), "utf8")).components as { id: string; version: string }[])
    .map((c) => [c.id, c.version]));

function used(): string[] {
  const set = new Set<string>(["mdm/org"]); // the shell's own: the legal entity switcher (FP10)
  const dir = join(repo, "modules");
  for (const name of existsSync(dir) ? readdirSync(dir) : []) {
    const pkg = join(dir, name, "package.json");
    if (!existsSync(pkg)) continue;
    const d = JSON.parse(readFileSync(pkg, "utf8")).bePageModule ?? {};
    for (const c of [d.component, ...(d.needs ?? []), ...(d.optional ?? [])]) if (c) set.add(c);
  }
  return [...set].sort();
}

const fileOf = (id: string) => id.replace("/", "-");
const wanted = process.argv.slice(2).length ? process.argv.slice(2) : used();
const contracts = join(repo, "packages/api/contracts");
const generated = join(repo, "packages/api/src/generated");
mkdirSync(generated, { recursive: true });
const index: string[] = [];
for (const id of wanted) {
  const version = baseline.get(id);
  if (!version) throw new Error(`${id} is not in the baseline`);
  const src = join(assembly, "components", id);
  let files: string;
  try {
    files = execFileSync("git", ["-C", src, "ls-tree", "-r", "--name-only", version, "contract"], { encoding: "utf8" });
  } catch {
    throw new Error(`${id}: no tag ${version} in ${src}`);
  }
  if (!files.split("\n").includes("contract/openapi.yaml")) {
    console.log(`skip ${id} ${version}: no contract/openapi.yaml`);
    continue;
  }
  const out = join(contracts, fileOf(id));
  rmSync(out, { recursive: true, force: true });
  mkdirSync(out, { recursive: true });
  // the document and what it refers to (the event schemas), not the system surface's protobuf and generated code
  const keep = ["contract/openapi.yaml", ...(files.split("\n").some((f) => f.startsWith("contract/events/")) ? ["contract/events"] : [])];
  execFileSync("tar", ["-x", "-C", out], { input: execFileSync("git", ["-C", src, "archive", version, ...keep]) });
  writeFileSync(join(out, "VERSION"), version + "\n");
  const ast = await openapiTS(new URL(`file://${join(out, "contract/openapi.yaml")}`));
  writeFileSync(join(generated, `${fileOf(id)}.ts`),
    `// Generated by packages/api/scripts/generate.ts from ${id} ${version}'s contract: do not edit.\n` + astToString(ast));
  index.push(`export type * as ${fileOf(id).replace(/-([a-z])/g, (_, c: string) => c.toUpperCase())} from "./generated/${fileOf(id)}.ts";`);
  console.log(`made ${id} ${version}`);
}
writeFileSync(join(repo, "packages/api/src/index.ts"),
  "// Generated by packages/api/scripts/generate.ts: the contracts' types, one namespace per component (FP07).\n" +
  'export type * from "./types.ts";\n' + (index.length ? index.join("\n") + "\n" : ""));
