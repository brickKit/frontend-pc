// FP03: which page modules go into the build. A module goes in when its component and every component it needs are in
// the baseline, and its contract's major version is the major version the baseline selects for its component; the
// rest are left out with the reason, and their code is not in the build at all (only included modules are imported).

export interface Baseline {
  components: Map<string, string>; // component ID -> exact version
}

/** What a page module's package.json declares under "bePageModule" (the one place these are written). */
export interface Declared {
  component: string;
  contract: number;
  needs?: string[];
  capabilities?: string[];
  optional?: string[];
}

export interface Candidate {
  name: string; // the directory under modules/
  declared: Declared;
}

export interface Composition {
  included: { name: string; component: string; version: string }[];
  excluded: { name: string; reason: string }[];
}

export function major(version: string): number {
  const m = /^(\d+)\./.exec(version);
  if (!m) throw new Error(`not a version: ${version}`);
  return Number(m[1]);
}

export function parseBaseline(doc: unknown): Baseline {
  const list = (doc as { components?: { id?: unknown; version?: unknown }[] } | null)?.components;
  if (!Array.isArray(list)) throw new Error("the baseline has no components list");
  const components = new Map<string, string>();
  for (const c of list) {
    if (typeof c.id !== "string" || typeof c.version !== "string") throw new Error(`a component without id or version`);
    if (components.has(c.id)) throw new Error(`${c.id} is listed twice`);
    components.set(c.id, c.version);
  }
  return { components };
}

export function compose(baseline: Baseline, candidates: Candidate[]): Composition {
  const out: Composition = { included: [], excluded: [] };
  for (const c of [...candidates].sort((a, b) => a.name.localeCompare(b.name))) {
    const d = c.declared;
    const version = baseline.components.get(d.component);
    const missing = [d.component, ...(d.needs ?? [])].filter((x) => !baseline.components.has(x));
    if (missing.length) {
      out.excluded.push({ name: c.name, reason: `not in the baseline: ${missing.join(", ")}` });
    } else if (major(version!) !== d.contract) {
      out.excluded.push({ name: c.name, reason: `${d.component} ${version} is contract ${major(version!)}, the module needs ${d.contract}` });
    } else {
      out.included.push({ name: c.name, component: d.component, version: version! });
    }
  }
  return out;
}

/** modules.generated.ts: the included modules imported by relative path, the composition written out as comments. */
export function generated(c: Composition, baselineFile: string): string {
  const lines = [
    `// Generated by packages/build (pnpm compose) from ${baselineFile}: do not edit (FP03).`,
    ...c.included.map((m) => `// included: ${m.name} (${m.component} ${m.version})`),
    ...c.excluded.map((m) => `// left out: ${m.name}: ${m.reason}`),
    `import type { PageModule } from "./module.ts";`,
    ...c.included.map((m, i) => `import m${i} from "../../../modules/${m.name}/src/module.ts";`),
    `export const modules: PageModule[] = [${c.included.map((_, i) => `m${i}`).join(", ")}];`,
  ];
  return lines.join("\n") + "\n";
}
