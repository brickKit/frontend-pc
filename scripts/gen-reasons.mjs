// packages/shell/src/reasons.generated.ts from be-protocol's platform reason catalog (vectors/errors.json): each
// reason's HTTP status and whether a caller may retry it (yes, no, query_first, after_refresh). FP08 classifies by it;
// a reason not in the table is treated as protective (never shown as success).
// Usage: node scripts/gen-reasons.mjs <be-protocol checkout>
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = process.argv[2];
if (!dir) throw new Error("usage: gen-reasons.mjs <be-protocol checkout>");
const doc = JSON.parse(readFileSync(join(dir, "vectors/errors.json"), "utf8"));
const rows = doc.cases.filter((c) => c.kind === "reason").sort((a, b) => a.reason.localeCompare(b.reason));
const out = [
  `// Generated by scripts/gen-reasons.mjs from be-protocol ${doc.protocol} (vectors/errors.json): do not edit.`,
  `export type Retry = "yes" | "no" | "query_first" | "after_refresh" | "none";`,
  `export const protocolVersion = ${JSON.stringify(doc.protocol)};`,
  `export const reasons: Readonly<Record<string, { http: number; retry: Retry }>> = {`,
  ...rows.map((c) => `  ${c.reason}: { http: ${c.http}, retry: ${JSON.stringify(c.retryable)} },`),
  `};`,
];
writeFileSync(new URL("../packages/shell/src/reasons.generated.ts", import.meta.url), out.join("\n") + "\n");
console.log(`${rows.length} reasons from be-protocol ${doc.protocol}`);
